"""Consistent error responses.

Every error has the shape:
    {"error": {"code": "SOME_CODE", "message": "Readable text", "details": ...}}
"""
from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException


class AppError(Exception):
    status_code = 400
    code = "BAD_REQUEST"

    def __init__(self, message: str, details=None):
        super().__init__(message)
        self.message = message
        self.details = details


class AccountNotFound(AppError):
    status_code = 404
    code = "ACCOUNT_NOT_FOUND"

    def __init__(self, account_id: str):
        super().__init__("Account not found. Please check the account ID.", {"account_id": account_id})


class InsufficientBalance(AppError):
    status_code = 422
    code = "INSUFFICIENT_BALANCE"


class DuplicateTransaction(AppError):
    status_code = 409
    code = "DUPLICATE_TRANSACTION"


class SameAccountTransfer(AppError):
    status_code = 400
    code = "SAME_ACCOUNT_TRANSFER"


def error_json(status_code: int, code: str, message: str, details=None) -> JSONResponse:
    return JSONResponse(
        status_code=status_code,
        content={"error": {"code": code, "message": message, "details": details}},
    )


# Field name -> specific error code, so clients can tell common problems apart.
_FIELD_CODES = {
    "type": "INVALID_TRANSACTION_TYPE",
    "amount": "INVALID_AMOUNT",
    "page": "INVALID_PAGINATION",
    "limit": "INVALID_PAGINATION",
}


# Readable names used in validation messages.
FIELD_LABELS = {
    "name": "Account holder name",
    "type": "Transaction type",
    "amount": "Amount",
    "reference_id": "Reference ID",
    "description": "Description",
    "from_account_id": "Source account",
    "to_account_id": "Destination account",
    "page": "Page",
    "limit": "Limit",
}

# Fields the client may never send, with the reason shown to them.
SERVER_MANAGED = {
    "balance": "Balance cannot be set. New accounts always start with a balance of 0.",
    "id": "ID is generated by the server and cannot be set.",
    "created_at": "Created date is set by the server and cannot be set.",
    "account_id": "Account is taken from the URL and cannot be set in the body.",
}


def _fmt_number(value) -> str:
    n = float(value)
    return f"{n:,.0f}" if n == int(n) else f"{n:,.2f}"


def _field_label(field: str) -> str:
    return FIELD_LABELS.get(field, field.replace("_", " ").capitalize())


def validation_message(err: dict) -> str:
    """Turn one Pydantic error into a standard, user-friendly sentence."""
    loc = [str(p) for p in err.get("loc", ()) if p not in ("body", "query", "path")]
    field = loc[-1] if loc else ""
    label = _field_label(field)
    kind = err.get("type", "")
    ctx = err.get("ctx") or {}

    if kind == "json_invalid":
        return "Request body must be valid JSON."
    if not field:
        if kind == "missing":
            return "Request body is required."
        return "Request body must be a JSON object."

    if kind == "missing" or err.get("input") is None:
        return f"{label} is required."
    if kind == "extra_forbidden":
        return SERVER_MANAGED.get(field, f"'{field}' is not an allowed field.")
    if kind == "string_too_short":
        n = ctx.get("min_length", 1)
        return f"{label} is required." if n <= 1 else f"{label} must be at least {n} characters."
    if kind == "string_too_long":
        return f"{label} must be at most {ctx.get('max_length')} characters."
    if kind == "string_type":
        return f"{label} must be text."
    if kind in ("enum", "literal_error"):
        return f"{label} must be either 'credit' or 'debit'."
    if kind in ("decimal_parsing", "decimal_type", "float_parsing", "float_type", "finite_number"):
        return f"{label} must be a valid number."
    if kind == "greater_than":
        gt = ctx.get("gt")
        return f"{label} must be greater than {_fmt_number(gt)}."
    if kind == "greater_than_equal":
        return f"{label} must be {_fmt_number(ctx.get('ge'))} or more."
    if kind == "less_than_equal":
        return f"{label} must not be more than {_fmt_number(ctx.get('le'))}."
    if kind == "decimal_max_places":
        return f"{label} can have at most {ctx.get('decimal_places')} decimal places."
    if kind == "decimal_max_digits":
        return f"{label} has too many digits."
    if kind in ("int_parsing", "int_type", "int_from_float"):
        return f"{label} must be a whole number."
    return f"{label} is invalid."


def _validation_code(errors: list[dict]) -> str:
    for err in errors:
        loc = err.get("loc", ())
        if err.get("type") == "json_invalid" or loc == ("body",):
            return "INVALID_REQUEST_BODY"
    # Use a specific code only when every problem is of that one kind
    # (e.g. only the amount is wrong). Missing fields are a general validation error.
    codes = {
        _FIELD_CODES.get(err["loc"][-1]) if err.get("loc") and err.get("type") != "missing" else None
        for err in errors
    }
    if len(codes) == 1 and None not in codes:
        return codes.pop()
    return "VALIDATION_ERROR"


def register_error_handlers(app: FastAPI) -> None:
    @app.exception_handler(AppError)
    async def _app_error(_: Request, exc: AppError):
        return error_json(exc.status_code, exc.code, exc.message, exc.details)

    @app.exception_handler(RequestValidationError)
    async def _validation_error(_: Request, exc: RequestValidationError):
        errors = exc.errors()
        details = []
        for err in errors:
            field = ".".join(str(p) for p in err.get("loc", ()) if p not in ("body", "query", "path"))
            msg = validation_message(err)
            if not any(d["field"] == field for d in details):  # one message per field
                details.append({"field": field, "message": msg})
        message = details[0]["message"] if len(details) == 1 else "Some fields are invalid. Please correct them and try again."
        return error_json(400, _validation_code(errors), message, details)

    @app.exception_handler(StarletteHTTPException)
    async def _http_error(_: Request, exc: StarletteHTTPException):
        known = {
            404: ("NOT_FOUND", "The requested resource was not found."),
            405: ("METHOD_NOT_ALLOWED", "This action is not allowed on this endpoint."),
        }
        code, message = known.get(exc.status_code, ("HTTP_ERROR", str(exc.detail)))
        return error_json(exc.status_code, code, message)

    @app.exception_handler(Exception)
    async def _unexpected(_: Request, __: Exception):
        return error_json(500, "INTERNAL_ERROR", "An unexpected error occurred.")
